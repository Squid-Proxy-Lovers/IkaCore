#!/usr/bin/env python3
"""Generate the supported public API inventory and live signatures."""
from __future__ import annotations

import inspect
import re
from importlib import import_module
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ("IkaCore", "IkaModel", "IkaMem", "IkaCore.testing")
EXTRA_EXPORTS = {
    "IkaCore.runtime_control": ("emit_tool_checkpoint",),
    "IkaCore.output_adapters": ("UsageAdapter",),
    "IkaCore.workflow": ("AsyncWorkflowExecutor",),
    "IkaMem.agent_tools": ("MemoryTools",),
}


def signature(value: Any) -> str:
    try:
        rendered = str(inspect.signature(value))
    except (ValueError, TypeError):
        return ""
    return re.sub(r" at 0x[0-9a-f]+", "", rendered)


def generate() -> str:
    lines = [
        "# Public API reference", "",
        "Generated by `python scripts/generate_api_reference.py`; pytest checks this file against the live exports and signatures.", "",
        "Use the import shown for each name. Private names and runtime component internals are unsupported.",
        "The [usage guide](USAGE.md) explains validators, chat turns, snapshots, thread scheduling, ownership and request bounds.", "",
        "`ExecutionLimits.context_budget` is a positive **token** count; `step_timeout` and request-control `timeout` use **seconds**.",
        "`ProviderConfig.client` is borrowed; `client_factory` creates a separately owned client for every agent/clone.",
        "`AgentResult` is the single final-check mapping; `validation` always reports `not_run`, `passed` or `failed`.",
        "`WorkflowResult.output` is execution output; `transcript` is replayable history (possibly compacted), and the instance maps retain every fan-out result.",
        "`IkaBaseAgent.send(message)` appends a turn; assigning `prompt` replaces the task and clears its transcript.",
        "A completed-snapshot resume restores conversation and returns saved output without a request. A pending-snapshot resume continues that turn.",
        "`IkaWorkflow.run(parallel=True, concurrency=N)` blocks while worker threads execute eligible instances.", "",
    ]
    modules = {name: tuple(import_module(name).__all__) for name in PACKAGES}
    modules.update(EXTRA_EXPORTS)
    for module_name, names in modules.items():
        lines += [f"## {module_name}", ""]
        module = import_module(module_name)
        for name in names:
            value = getattr(module, name)
            lines += [f"### `{module_name}.{name}`", "", f"Import: `from {module_name} import {name}`.", ""]
            sig = signature(value)
            if sig:
                lines += ["```python", name + sig, "```", ""]
            elif not inspect.isclass(value):
                lines += [f"Value type: `{type(value).__name__}`.", ""]
            doc = inspect.getdoc(value) if callable(value) else None
            if doc and (getattr(value, "__module__", "") or "").startswith(("Ika",)):
                lines += [doc.split("\n\n")[0], ""]
            if not inspect.isclass(value):
                continue
            annotations = getattr(value, "__annotations__", {})
            fields = [key for key in annotations if not key.startswith("_")]
            if fields:
                lines += ["Declared fields: " + ", ".join(f"`{field}`" for field in fields) + ".", ""]
            properties = [key for key, item in inspect.getmembers(value) if isinstance(item, property) and not key.startswith("_")]
            if properties:
                lines += ["Properties: " + ", ".join(f"`{key}`" for key in properties) + ".", ""]
            for method_name, method in inspect.getmembers(value, callable):
                if method_name.startswith("_") or not (getattr(method, "__module__", "") or "").startswith(("Ika",)):
                    continue
                lines += [f"- `{name}.{method_name}{signature(method)}`"]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    (ROOT / "docs" / "API.md").write_text(generate(), encoding="utf-8")
